// The Fatoora onboarding HTTP client: compliance CSID, compliance checks, production CSID, and
// renewal. Endpoints, headers, and the request/response JSON shape are corroborated by two
// independent sources — this task's own brief and a Microsoft Dynamics 365 onboarding guide's
// complete worked example (fetched 2026-11-05) — not just one secondary source.
// `requestComplianceCsid` is now CONFIRMED against the real sandbox: a real call issued a real
// compliance CSID (docs/01-OPEN-DECISIONS.md section X). `submitComplianceInvoice`/
// `requestProductionCsid`/`renewProductionCsid` are // REVIEW: still unconfirmed — none of them
// has been exercised against the real sandbox yet.
import { ZATCA_BASE_URL, type ZatcaEnvironment } from "../submission/zatca-environment.js";
import { FetchHttpTransport, classifyErrorStatus, DEFAULT_ZATCA_TIMEOUT_MS, type HttpTransport } from "../http/zatca-http-transport.js";
import type { ZatcaCredentials } from "../submission/zatca-api-client.js";
import type { ClearanceRequestBody, ValidationResults } from "../submission/zatca-api-client.js";

export interface CsidResponseBody {
  readonly requestID: string;
  readonly dispositionMessage?: string;
  // The certificate's body, base64 — NOT itself PEM-armored (confirmed by the Microsoft
  // reference script, which wraps it in "-----BEGIN CERTIFICATE-----"/"-----END..." before
  // using it). Encrypted at rest immediately by whoever calls this client — see
  // onboarding.service.ts, never logged or returned further up by any API of ours
  // (docs/09-SECURITY-RULES.md §5).
  readonly binarySecurityToken: string;
  readonly secret: string;
}

export interface ComplianceCheckResponseBody {
  readonly clearanceStatus?: "CLEARED" | "NOT_CLEARED";
  readonly reportingStatus?: "REPORTED" | "NOT_REPORTED";
  readonly validationResults: ValidationResults;
}

function authHeader(credentials: ZatcaCredentials): string {
  return `Basic ${Buffer.from(`${credentials.binarySecurityToken}:${credentials.secret}`).toString("base64")}`;
}

export class ZatcaOnboardingApiClient {
  constructor(
    private readonly environment: ZatcaEnvironment,
    private readonly transport: HttpTransport = new FetchHttpTransport(),
    private readonly timeoutMs: number = DEFAULT_ZATCA_TIMEOUT_MS,
  ) {}

  // POST /compliance — the OTP (generated by the taxpayer in the FATOORA portal, or the fixed
  // sandbox value) authenticates this ONE call; every later onboarding call authenticates with
  // the CSID it returns instead.
  async requestComplianceCsid(otp: string, csrBase64: string, acceptLanguage: "ar" | "en" = "en"): Promise<CsidResponseBody> {
    const url = `${ZATCA_BASE_URL[this.environment]}/compliance`;
    const headers = { Accept: "application/json", OTP: otp, "Accept-Version": "V2", "Accept-Language": acceptLanguage };
    const response = await this.transport.request("POST", url, headers, { csr: csrBase64 }, this.timeoutMs);
    if (response.status < 200 || response.status >= 300) throw classifyErrorStatus(response.status, response.body);
    return response.body as CsidResponseBody;
  }

  // POST /compliance/invoices — one call per sample document the compliance check requires.
  // Authenticates with the compliance CSID just issued, same request body shape as a real
  // clearance/reporting submission (packages/compliance/zatca-sa/src/submission).
  async submitComplianceInvoice(credentials: ZatcaCredentials, body: ClearanceRequestBody, acceptLanguage: "ar" | "en" = "en"): Promise<ComplianceCheckResponseBody> {
    const url = `${ZATCA_BASE_URL[this.environment]}/compliance/invoices`;
    const headers = { Accept: "application/json", Authorization: authHeader(credentials), "Accept-Version": "V2", "Accept-Language": acceptLanguage };
    const response = await this.transport.request("POST", url, headers, body, this.timeoutMs);
    if (response.status < 200 || response.status >= 300) throw classifyErrorStatus(response.status, response.body);
    return response.body as ComplianceCheckResponseBody;
  }

  // POST /production/csids — issues the production CSID once every compliance check has passed.
  async requestProductionCsid(credentials: ZatcaCredentials, complianceRequestId: string, acceptLanguage: "ar" | "en" = "en"): Promise<CsidResponseBody> {
    const url = `${ZATCA_BASE_URL[this.environment]}/production/csids`;
    const headers = { Accept: "application/json", Authorization: authHeader(credentials), "Accept-Version": "V2", "Accept-Language": acceptLanguage };
    const response = await this.transport.request("POST", url, headers, { compliance_request_id: complianceRequestId }, this.timeoutMs);
    if (response.status < 200 || response.status >= 300) throw classifyErrorStatus(response.status, response.body);
    return response.body as CsidResponseBody;
  }

  // PATCH /production/csids — renews an expiring production CSID with a fresh CSR and a new OTP.
  // Authenticates with the CURRENT (about-to-expire) production CSID, not the OTP alone — // REVIEW:
  // this task's brief only says "PATCH /production/csids with a new OTP"; whether the OTP
  // replaces or supplements the existing CSID's Basic auth is unconfirmed (no reference
  // implementation for renewal specifically was found, unlike the two other calls above).
  async renewProductionCsid(credentials: ZatcaCredentials, otp: string, csrBase64: string, acceptLanguage: "ar" | "en" = "en"): Promise<CsidResponseBody> {
    const url = `${ZATCA_BASE_URL[this.environment]}/production/csids`;
    const headers = { Accept: "application/json", Authorization: authHeader(credentials), OTP: otp, "Accept-Version": "V2", "Accept-Language": acceptLanguage };
    const response = await this.transport.request("PATCH", url, headers, { csr: csrBase64 }, this.timeoutMs);
    if (response.status < 200 || response.status >= 300) throw classifyErrorStatus(response.status, response.body);
    return response.body as CsidResponseBody;
  }
}
